namespace Instrumentation\DependencyInjection;

use OpenTelemetry\SemConv\Attributes\ServiceAttributes;
use Symfony\Component\Config\Definition\Builder\TreeBuilder;
use Symfony\Component\Config\Definition\ConfigurationInterface;

class Configuration implements ConfigurationInterface
{
    public function getConfigTreeBuilder(): TreeBuilder
    {
        $treeBuilder = new TreeBuilder('instrumentation');

        $treeBuilder->getRootNode() // @phpstan-ignore-line
            ->addDefaultsIfNotSet()
            ->children()

                ->arrayNode('resource')
                    ->info('Use semantic tags defined in the OpenTelemetry specification (https://github.com/open-telemetry/opentelemetry-specification/blob/main/specification/resource/semantic_conventions/README.md)')
                    ->example([
                        ServiceAttributes::SERVICE_NAME => 'my_instrumented_app',
                        ServiceAttributes::SERVICE_VERSION => '1.2.3',
                    ])
                    ->variablePrototype()->end()
                    ->defaultValue([
                        ServiceAttributes::SERVICE_NAME => '%env(default:instrumentation.default_service_name:OTEL_SERVICE_NAME)%',
                    ])
                ->end()

                ->arrayNode('baggage')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')->defaultFalse()->end()
                    ->end()
                ->end()

                ->arrayNode('logging')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')->defaultTrue()->end()
                        ->booleanNode('flush_after_request')
                            ->info('Whether log records should be exported after each request (kernel.terminate)')
                            ->defaultTrue()
                        ->end()
                    ->end()
                ->end()

                ->arrayNode('tracing')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')->defaultTrue()->end()
                        ->scalarNode('trace_url')
                            ->info('Allows you to have links to your traces generated in error messages and twig.')
                            ->example('http://localhost:16682/trace/{traceId}')
                        ->end()
                        ->arrayNode('redacted_query_parameters')
                            ->info('Query parameters whose values are redacted from span URLs (outgoing `url.full`, incoming `url.query`), case-insensitively, on top of the defaults (key, api_key, token, sig, X-Goog-Signature...). Per outgoing request: the `redacted_query_parameters` extra option.')
                            ->defaultValue([])
                            ->scalarPrototype()->end()
                            ->example(['appid', 'session'])
                        ->end()
                        ->arrayNode('request')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->booleanNode('flush_spans_after_terminate')
                                    ->info('Whether exporter should be flushed after each request (kernel.terminate)')
                                    ->defaultTrue()
                                ->end()
                                ->arrayNode('attributes')
                                    ->addDefaultsIfNotSet()
                                    ->children()
                                        ->scalarNode('server_name')
                                            ->defaultNull()
                                            ->info('Use the primary server name of the matched virtual host')
                                            ->example('example.com')

                                        ->end()
                                        ->arrayNode('request_headers')
                                            ->info('Incoming request headers to add as span attributes')
                                            ->defaultValue([])
                                            ->scalarPrototype()->end()
                                            ->example([
                                                'accept',
                                                'accept-encoding',
                                            ])
                                        ->end()
                                        ->booleanNode('user')
                                            ->info('Whether to add the `user.id` and `user.roles` attributes')
                                            ->defaultTrue()
                                        ->end()
                                    ->end()
                                ->end()
                                ->arrayNode('blacklist')
                                    ->defaultValue([
                                        '^/_fragment',
                                        '^/_profiler',
                                        '^/_wdt',
                                    ])
                                    ->scalarPrototype()->end()
                                ->end()
                                ->arrayNode('methods')
                                    ->defaultValue([
                                        'GET',
                                        'POST',
                                        'PUT',
                                        'DELETE',
                                        'PATCH',
                                    ])
                                    ->scalarPrototype()->end()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('command')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->arrayNode('blacklist')
                                    ->defaultValue([
                                        '^cache:clear$',
                                        '^assets:install$',
                                    ])
                                    ->scalarPrototype()->end()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('message')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->booleanNode('flush_spans_after_handling')
                                    ->info('Whether exporter should be flushed after each message')
                                    ->defaultTrue()
                                ->end()
                                ->arrayNode('blacklist')
                                    ->defaultValue([])
                                    ->scalarPrototype()->end()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('http')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultTrue()->end()
                                ->booleanNode('propagate_by_default')
                                    ->info('Whether trace context should be propagated by default for outgoing requests')
                                    ->defaultTrue()
                                ->end()
                                ->arrayNode('attributes')
                                    ->addDefaultsIfNotSet()
                                    ->children()
                                        ->arrayNode('request_headers')
                                            ->info('Outgoing request headers to add as span attributes')
                                            ->defaultValue([])
                                            ->scalarPrototype()->end()
                                            ->example([
                                                'accept',
                                                'accept-encoding',
                                            ])
                                        ->end()
                                    ->end()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('ai')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultFalse()->end()
                                ->arrayNode('platform')
                                    ->addDefaultsIfNotSet()
                                    ->children()
                                        ->arrayNode('blacklist')
                                            ->info('Models (regex) to exclude from tracing')
                                            ->defaultValue([])
                                            ->scalarPrototype()->end()
                                        ->end()
                                    ->end()
                                ->end()
                                ->arrayNode('agent')
                                    ->addDefaultsIfNotSet()
                                    ->children()
                                        ->arrayNode('blacklist')
                                            ->info('Agent names (regex) to exclude from tracing')
                                            ->defaultValue([])
                                            ->scalarPrototype()->end()
                                        ->end()
                                    ->end()
                                ->end()
                                ->arrayNode('tool')
                                    ->addDefaultsIfNotSet()
                                    ->children()
                                        ->arrayNode('blacklist')
                                            ->info('Tool names (regex) to exclude from tracing')
                                            ->defaultValue([])
                                            ->scalarPrototype()->end()
                                        ->end()
                                    ->end()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('doctrine')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('instrumentation')->defaultFalse()->end()
                                ->booleanNode('propagation')->defaultFalse()->end()
                                ->booleanNode('log_queries')->defaultFalse()->end()
                                ->integerNode('min_duration_ms')
                                    ->defaultValue(0)
                                    ->min(0)
                                    ->info('The shortest statement, in milliseconds, that is a span of its own; 0 makes every statement one. Every statement is counted either way (db.statements.count, db.statements.total_ms and db.statements.spans on the request, command or message).')
                                ->end()
                                ->arrayNode('connections')
                                    ->defaultValue([])
                                    ->scalarPrototype()->end()
                                ->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()

                ->arrayNode('profiling')
                    ->info('Continuous profiling of requests (Excimer sampling, pushed to Pyroscope): one profile per sampled request, linked to its trace. Needs ext-excimer; a profile is only taken while `active` and the extension is loaded.')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')
                            ->info('Registers the profiler. Static (read when the container is built): turn it on everywhere and switch profiling per environment with `active`.')
                            ->defaultFalse()
                        ->end()
                        ->booleanNode('active')
                            ->info('Runtime switch, usually an environment variable, so one image profiles where it is told to.')
                            ->example('%env(bool:PROFILING_ENABLED)%')
                            ->defaultTrue()
                        ->end()
                        ->integerNode('frequency')
                            ->info('Samples per second inside a profiled request. 20 to 100 showed no measurable overhead.')
                            ->defaultValue(50)
                        ->end()
                        ->floatNode('request_rate')
                            ->info('Share of requests profiled, 0 to 1. 0 profiles only the requests carrying the on-demand token.')
                            ->defaultValue(1.0)
                        ->end()
                        ->enumNode('clock')
                            ->info('`wall` answers where the time went (waiting on a database counts), `cpu` only the time the thread ran.')
                            ->values(['wall', 'cpu'])
                            ->defaultValue('wall')
                        ->end()
                        ->integerNode('max_depth')->info('Deepest stack kept.')->defaultValue(256)->end()
                        ->arrayNode('on_demand')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->scalarNode('token')
                                    ->info('A request carrying this secret in `header` is always profiled. Empty: off. Keep it a secret (an environment variable).')
                                    ->defaultValue('')
                                ->end()
                                ->booleanNode('statements')
                                    ->info('A request carrying the token also has its SQL statements captured as events of its main span (`db.statement`: text, duration, database; at most 100): which statements a page runs and which cost the most, with no span per statement. Prepared text only, the literals of a statement run as it is masked. Needs tracing.doctrine. Off by default: a statement is not data to put in a trace unasked.')
                                    ->defaultFalse()
                                ->end()
                                ->scalarNode('header')->defaultValue('X-Profile-Token')->end()
                            ->end()
                        ->end()
                        ->scalarNode('span_attribute')
                            ->info('The attribute set on the main span with the id of its profile: what makes Grafana show "Profiles for this span". Empty: not set.')
                            ->defaultValue('pyroscope.profile.id')
                        ->end()
                        ->arrayNode('pyroscope')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->scalarNode('url')
                                    ->info('Base URL of the Pyroscope (or of an Alloy pyroscope.receive_http). Empty: profiles are taken and dropped.')
                                    ->example('http://pyroscope:4040')
                                    ->defaultValue('')
                                ->end()
                                ->scalarNode('application')->info('The series name (the service_name label).')->defaultValue('%service.name%')->end()
                                ->scalarNode('environment')->info('The `env` label. Empty: none.')->defaultValue('')->end()
                                ->integerNode('upload_deadline_ms')
                                    ->info('How long the body of a profile may take to go out (name lookup, connect, upload) after the response; the answer is never waited for.')
                                    ->defaultValue(150)
                                ->end()
                                ->integerNode('max_in_flight')->info('Uploads pending at once; past that a profile is dropped.')->defaultValue(8)->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()

                ->arrayNode('metrics')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')->defaultTrue()->end()
                        ->arrayNode('message')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultFalse()->end()
                            ->end()
                        ->end()
                        ->arrayNode('request')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultFalse()->end()
                                ->integerNode('flush_interval')
                                    ->info('Minimum seconds between two metrics exports at the end of a request (kernel.terminate), 0 to export after every request')
                                    ->defaultValue(10)
                                    ->min(0)
                                ->end()
                                ->arrayNode('blacklist')
                                    ->defaultValue([
                                        '^/_fragment',
                                        '^/_profiler',
                                        '^/_wdt',
                                    ])
                                    ->scalarPrototype()->end()
                                ->end()
                            ->end()
                        ->end()
                        ->arrayNode('ai')
                            ->addDefaultsIfNotSet()
                            ->children()
                                ->booleanNode('enabled')->defaultFalse()->end()
                            ->end()
                        ->end()
                    ->end()
                ->end()

            ->end()
        ->end();

        return $treeBuilder;
    }
}
